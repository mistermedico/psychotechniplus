// ── Helpers ────────────────────────────────────────────────────────────────

export function getTargetById(id: string): Target | undefined {
  return TARGETS.find(t => t.id === id);
}

export function getTopicsByTarget(targetId: string): Topic[] {
  return TOPICS.filter(t => t.targetId === targetId);
}

export function getQuestionsByTopic(topicId: string): Question[] {
  return QUESTIONS.filter(q => q.topicId === topicId);
}

export function getQuestionsByTarget(targetId: string): Question[] {
  return QUESTIONS.filter(q => q.targetIds.includes(targetId));
}

export function getQuestionById(id: string): Question | undefined {
  return QUESTIONS.find(q => q.id === id);
}

export function getTopicById(id: string): Topic | undefined {
  return TOPICS.find(t => t.id === id);
}

export function getQuestionsForPractice(
  topicId: string,
  count = 10,
  userElo = 1200
): Question[] {
  const pool = getQuestionsByTopic(topicId);
  // Sort by ELO proximity to user's ELO (optimal learning zone ±150)
  const sorted = [...pool].sort((a, b) => {
    const da = Math.abs(a.psychometricStats.elo - userElo);
    const db = Math.abs(b.psychometricStats.elo - userElo);
    return da - db;
  });
  return sorted.slice(0, count);
}
